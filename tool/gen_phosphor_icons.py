"""Writes lib/widgets/phosphor_icons.dart with every Phosphor icon the app uses.

Use an icon as PhosphorIconsRegular.<name>, PhosphorIconsBold.<name> or
PhosphorIconsFill.<name> (names as on https://phosphoricons.com, in camelCase),
then run from the project root:

    python3 tool/gen_phosphor_icons.py

Codepoints come from the phosphor_flutter 2.1.0 sources (download them once with
`dart pub cache add phosphor_flutter --version 2.1.0`). The package itself is not a
dependency: it does not compile on current Flutter, so the app bundles its fonts
(fonts/Phosphor-*.ttf) and this generated class instead.
"""
import glob
import os
import re
import sys

SRC = os.path.expanduser('~/.pub-cache/hosted/pub.dev/phosphor_flutter-2.1.0/lib/src/')
STYLES = {  # class suffix -> (source file, font family in pubspec.yaml)
    'Regular': ('phosphor_icons_regular.dart', 'PhosphorRegular'),
    'Bold': ('phosphor_icons_bold.dart', 'PhosphorBold'),
    'Fill': ('phosphor_icons_fill.dart', 'PhosphorFill'),
}
OUT = 'lib/widgets/phosphor_icons.dart'

used = {style: set() for style in STYLES}
for path in glob.glob('lib/**/*.dart', recursive=True):
    if path == OUT:
        continue
    for style, name in re.findall(r'PhosphorIcons(Regular|Bold|Fill)\.([a-zA-Z0-9]+)', open(path).read()):
        used[style].add(name)

lines = [
    "import 'package:flutter/widgets.dart';",
    '',
    '/// The Phosphor icons the app uses (https://phosphoricons.com, MIT licence in',
    '/// fonts/LICENSE-phosphor.txt), drawn from the bundled Phosphor fonts.',
    '/// Generated by tool/gen_phosphor_icons.py: do not edit by hand.',
    '',
]
missing = []
for style, (src, family) in STYLES.items():
    text = open(SRC + src).read()
    lines += [f'class PhosphorIcons{style} {{', f'  PhosphorIcons{style}._();', f"  static const _family = '{family}';"]
    for name in sorted(used[style]):
        m = re.search(r'static const ' + name + r' = PhosphorFlatIconData\((0x[0-9a-f]+)', text)
        if m:
            lines.append(f'  static const {name} = IconData({m.group(1)}, fontFamily: _family);')
        else:
            missing.append(f'PhosphorIcons{style}.{name}')
    lines += ['}', '']
open(OUT, 'w').write('\n'.join(lines))
print(f'{OUT}: {sum(len(v) for v in used.values())} icons')
if missing:
    sys.exit('Not in Phosphor: ' + ', '.join(missing))
